export function getGameById(id) {
  return GAMES.find(function(g) { return g.id === id; });
}

export function getGamesByCategory(category) {
  return GAMES.filter(function(g) { return g.category === category; });
}

export function getPopularGames(limit) {
  var l = limit || 10;
  return GAMES.filter(function(g) { return g.popular; }).slice(0, l);
}

export function searchGames(query) {
  var q = query.toLowerCase();
  return GAMES.filter(function(g) {
    return (
      g.name.toLowerCase().includes(q) ||
      g.shortName.toLowerCase().includes(q) ||
      g.tags.some(function(t) { return t.toLowerCase().includes(q); })
    );
  });
}

export function getTotalStats() {
  return {
    totalGames: GAMES.length,
    totalPlayers: GAMES.reduce(function(s, g) { return s + g.activePlayers; }, 0),
    totalBets: GAMES.reduce(function(s, g) { return s + g.openBets; }, 0),
    totalPrize: GAMES.reduce(function(s, g) { return s + g.topPrize; }, 0)
  };
}
